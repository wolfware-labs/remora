//! `cargo xtask fold-table [--check]`: generates the full case folding table of
//! `remora_fs::path` from `xtask/data/CaseFolding.txt`, or checks that the
//! committed table matches it.

use std::fmt::Write as _;
use std::path::Path;

/// Where the generated table lives, relative to the workspace root.
pub const TABLE: &str = "crates/remora-fs/src/path/fold_table.rs";
/// The Unicode data it is generated from, relative to the workspace root.
pub const DATA: &str = "xtask/data/CaseFolding.txt";

/// The `C` and `F` mappings of `CaseFolding.txt` (full case folding), sorted by
/// code point, and the Unicode version from its first line.
pub fn parse(data: &str) -> Result<(String, Vec<(char, String)>), String> {
    let version = data
        .lines()
        .next()
        .and_then(|line| line.strip_prefix("# CaseFolding-"))
        .and_then(|rest| rest.strip_suffix(".txt"))
        .ok_or("the first line does not name CaseFolding-<version>.txt")?
        .to_owned();
    let mut pairs = Vec::new();
    for (n, line) in data.lines().enumerate() {
        let line = line.split('#').next().unwrap_or_default().trim();
        if line.is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split(';').map(str::trim).collect();
        let [code, status, mapping, ..] = fields[..] else {
            return Err(format!("line {}: expected `code; status; mapping;`", n + 1));
        };
        if status != "C" && status != "F" {
            continue;
        }
        let from = scalar(code).ok_or_else(|| format!("line {}: bad code point", n + 1))?;
        let to = mapping
            .split_whitespace()
            .map(scalar)
            .collect::<Option<String>>()
            .ok_or_else(|| format!("line {}: bad mapping", n + 1))?;
        pairs.push((from, to));
    }
    pairs.sort_unstable();
    if pairs.windows(2).any(|w| w[0].0 == w[1].0) {
        return Err("a code point has two C or F mappings".to_owned());
    }
    Ok((version, pairs))
}

fn scalar(hex: &str) -> Option<char> {
    char::from_u32(u32::from_str_radix(hex, 16).ok()?)
}

/// The Rust source of the table.
pub fn render(version: &str, pairs: &[(char, String)]) -> String {
    let mut out = format!(
        "//! Full case folding: the `C` and `F` mappings of Unicode {version}\n\
         //! `CaseFolding.txt`. Generated by `cargo xtask fold-table`; do not edit.\n\n\
         /// `(from, to)` pairs, sorted by `from`.\n\
         #[rustfmt::skip]\n\
         pub(super) const FULL_FOLD: &[(char, &str)] = &[\n"
    );
    for (from, to) in pairs {
        let to: String = to
            .chars()
            .map(|c| format!("\\u{{{:04X}}}", c as u32))
            .collect();
        let _ = writeln!(out, "    ('\\u{{{:04X}}}', \"{to}\"),", *from as u32);
    }
    out.push_str("];\n");
    out
}

/// Writes the table, or with `check` reports whether the committed one is current.
pub fn run(root: &Path, check: bool) -> Result<String, String> {
    let data = std::fs::read_to_string(root.join(DATA)).map_err(|e| format!("{DATA}: {e}"))?;
    let (version, pairs) = parse(&data).map_err(|e| format!("{DATA}: {e}"))?;
    let table = render(&version, &pairs);
    let path = root.join(TABLE);
    if check {
        let committed = std::fs::read_to_string(&path).map_err(|e| format!("{TABLE}: {e}"))?;
        if committed != table {
            return Err(format!("{TABLE} is stale; run `cargo xtask fold-table`"));
        }
        return Ok(format!(
            "fold-table: Unicode {version}, {} mappings, current",
            pairs.len()
        ));
    }
    std::fs::write(&path, table).map_err(|e| format!("{TABLE}: {e}"))?;
    Ok(format!(
        "fold-table: Unicode {version}, {} mappings, written",
        pairs.len()
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "# CaseFolding-18.0.0.txt\n\
        # comment\n\
        \n\
        0041; C; 0061; # LATIN CAPITAL LETTER A\n\
        00DF; F; 0073 0073; # LATIN SMALL LETTER SHARP S\n\
        0130; T; 0069; # LATIN CAPITAL LETTER I WITH DOT ABOVE\n\
        1E9E; S; 00DF; # LATIN CAPITAL LETTER SHARP S\n\
        1E9E; F; 0073 0073; # LATIN CAPITAL LETTER SHARP S\n";

    #[test]
    fn keeps_only_common_and_full() {
        let (version, pairs) = parse(SAMPLE).unwrap();
        assert_eq!(version, "18.0.0");
        let expected = [('A', "a"), ('\u{DF}', "ss"), ('\u{1E9E}', "ss")];
        assert_eq!(pairs, expected.map(|(c, s)| (c, s.to_owned())));
    }

    #[test]
    fn duplicate_mapping_refused() {
        let data = format!("{SAMPLE}0041; F; 0062;\n");
        assert!(parse(&data).is_err());
    }

    #[test]
    fn renders_escaped_pairs() {
        let out = render("18.0.0", &[('\u{DF}', "ss".to_owned())]);
        assert!(out.contains("Unicode 18.0.0"), "{out}");
        assert!(
            out.contains("    ('\\u{00DF}', \"\\u{0073}\\u{0073}\"),\n"),
            "{out}"
        );
    }
}
